// AboutText.cs -- what the program has to say about where it came from.
//
// Kept apart from Shell.cs because it is writing, not code, and because it is
// long. The shell knows how to draw a chapter; this file knows what is in one.
//
// A block is a line of text, with the first two characters saying what kind:
//
//     # heading        a heading inside the chapter
//     > quotation      something somebody actually said or wrote
//     @ url | title | what you will find there
//     anything else    a paragraph
//
// Nothing here is invented. Every claim about Avidan is one this program can
// reproduce on demand -- the section called "the fragments David Avidan
// published in 1974" in the test suite is the same nine lines -- and every
// link was fetched before it was written down.

