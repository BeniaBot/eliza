        public static string[] Chapters
        {
            get
            {
                return Say.Hebrew
                    ? new[] { "מיהי אלייזה", "וייצנבאום", "איך זה עובד", "אפקט אלייזה",
                              "אבידן", "העברית", "שי-בוטים", "נאמנות",
                              "זו בינה מלאכותית?", "לקריאה" }
                    : new[] { "What it is", "Weizenbaum", "How it works", "The ELIZA effect",
                              "Avidan", "The Hebrew", "The clones", "Fidelity",
                              "Is this AI?", "Further reading" };
            }
        }

        public static IEnumerable<string> Chapter(int n)
        {
            return Say.Hebrew ? Hebrew(n) : English(n);
        }

