# Lifts the reference implementation's lowercase-to-uppercase table into C#.
#
# .NET's own char.ToUpperInvariant is not the same table. Greek final sigma is
# the case that bites: .NET leaves U+03C2 alone, this table folds it to U+03A3,
# so a Greek script's keywords would never match. The table itself comes from
# the toupper list in ISO/IEC 30112 WD10.

import io
import re
import sys

SRC = 'reference/eliza_reference.cpp'
OUT = 'src/CaseTable.cs'

text = io.open(SRC, encoding='utf-8', errors='replace').read()

start = text.index('static const uint32_t lower_upper[] = {')
start = text.index('{', start) + 1
end = text.index('};', start)
body = text[start:end]

values = re.findall(r'0x([0-9A-Fa-f]+)UL', body)
if len(values) % 2:
    sys.exit('odd number of values: the table is not in pairs')

pairs = [(int(values[i], 16), int(values[i + 1], 16))
         for i in range(0, len(values), 2)]

# The lookup walks forward while c32 > table[i], so the table must ascend.
for a, b in zip(pairs, pairs[1:]):
    if b[0] <= a[0]:
        sys.exit('table is not sorted at U+%04X -> U+%04X' % (a[0], b[0]))

out = []
out.append('// Generated by build/extract_case_table.py from the reference')
out.append('// implementation at github.com/anthay/ELIZA. Do not edit by hand.')
out.append('//')
out.append('// ELIZA uppercases everything, and which table it uppercases with is')
out.append('// visible behaviour: a keyword only matches if the input folds to the same')
out.append('// letters. .NET disagrees with this table in both directions -- Greek final')
out.append('// sigma is the clearest case -- so the table travels with the engine.')
out.append('')
out.append('namespace ElizaApp')
out.append('{')
out.append('    static class CaseTable')
out.append('    {')
out.append('        // Lower, upper, lower, upper, ascending by the lower code point.')
out.append('        public static readonly uint[] LowerUpper = {')

for i in range(0, len(pairs), 4):
    chunk = pairs[i:i + 4]
    out.append('            ' + ' '.join('0x%04X, 0x%04X,' % p for p in chunk))

out.append('        };')
out.append('')
out.append('        public static uint Upper(uint c)')
out.append('        {')
out.append('            int last = LowerUpper.Length - 2, i = 0;')
out.append('            while (i < last && c > LowerUpper[i]) i += 2;')
out.append('            return c == LowerUpper[i] ? LowerUpper[i + 1] : c;')
out.append('        }')
out.append('    }')
out.append('}')

io.open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
sys.stderr.write('%d pairs -> %s\n' % (len(pairs), OUT))
