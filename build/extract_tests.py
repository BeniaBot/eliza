# Pull the reference implementation's test conversations out of eliza.cpp and
# emit them as C# data. These are the yardstick: if our engine reproduces every
# one of these exchanges character for character, it behaves like the original.

import re
import io
import sys

SRC = 'scripts/eliza_reference.cpp'
OUT = 'src/Conversations.cs'

BS = chr(92)      # backslash
DQ = chr(34)      # double quote

lines = io.open(SRC, encoding='utf-8', errors='replace').read().split('\n')

# Inside a character class a backslash must itself be escaped, so these
# fragments need two backslash characters, not one.
ESC = BS + BS
STRING_LITERAL = r'(?:"(?:[^"' + ESC + r']|' + ESC + r'.)*"\s*)+'
PAIR = re.compile(r'\{\s*(' + STRING_LITERAL + r'),\s*(' + STRING_LITERAL + r')\s*\}')
PIECE = re.compile(r'"((?:[^"' + ESC + r']|' + ESC + r'.)*)"')


def collect(first, last):
    """Every { "prompt", "response" } pair in the given 1-based line range."""
    text = '\n'.join(lines[first - 1:last])
    text = re.sub(r'/' + r'\*.*?\*' + r'/', '', text, flags=re.S)   # block comments
    text = re.sub(r'//[^\n]*', '', text)                            # line comments
    return PAIR.findall(text)


def to_csharp(literal):
    """Adjacent C++ string literals -> a single C# literal."""
    joined = ''.join(PIECE.findall(literal))
    # undo C++ escapes
    joined = joined.replace(BS + DQ, DQ)
    joined = joined.replace(BS + "'", "'")
    joined = joined.replace(BS + BS, BS)
    # redo them for C#
    joined = joined.replace(BS, BS + BS).replace(DQ, BS + DQ)
    return DQ + joined + DQ


SETS = [
    ('Cacm1966', 4794, 4854, 'the conversation printed in the 1966 CACM paper'),
    ('HayContinued', 5610, 5678, 'an imagined continuation, Hay 2023'),
    ('Turingish', 5680, 5726, 'straying from the psychiatric context, Hay 2026'),
    ('AltMenAlike', 5742, 5788, 'a typescript found in Box 8 of the MIT archive'),
    ('VeryUnhappy', 5801, 5836, 'the conversation in the August 1965 paper'),
    ('EveryRule', 5845, 6387, 'an exchange for every rule in the DOCTOR script'),
]

out = []
out.append('// Generated by build/extract_tests.py from the reference')
out.append('// implementation at github.com/anthay/ELIZA. Do not edit by hand.')
out.append('')
out.append('namespace ElizaApp')
out.append('{')
out.append('    static class Conversations')
out.append('    {')

total = 0
for name, first, last, note in SETS:
    pairs = collect(first, last)
    total += len(pairs)
    sys.stderr.write('%-14s %3d exchanges\n' % (name, len(pairs)))
    out.append('        // ' + note)
    out.append('        public static readonly string[,] ' + name + ' = {')
    for prompt, response in pairs:
        out.append('            { ' + to_csharp(prompt) + ',')
        out.append('              ' + to_csharp(response) + ' },')
    out.append('        };')
    out.append('')

out.append('    }')
out.append('}')

io.open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
sys.stderr.write('%-14s %3d exchanges total -> %s\n' % ('', total, OUT))
